export let add = (a, b) => {
    let sumAnswer = a + b;
    return sumAnswer;
}
export let subtract = (a, b) => {
    let subtractAnswer = a - b;
    return subtractAnswer;
}
export let product = (a, b) => {
    let productAnswer = a * b;
    return productAnswer;
}
export let division = (a, b) => {
    let divisionAnswer = a/b;
    return divisionAnswer;
}